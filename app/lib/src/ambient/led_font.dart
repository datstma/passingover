/// `text` in characters the font can draw: upper case, accents folded.
String ledText(String text) {
  final out = StringBuffer();
  for (final rune in text.runes) {
    var c = String.fromCharCode(rune);
    if (c == 'ß') c = 'SS';
    c = c.toUpperCase();
    c = _folded[c] ?? c;
    for (final ch in c.split('')) {
      out.write(_glyphs.containsKey(ch) ? ch : ' ');
    }
  }
  return out.toString();
}

/// Whether the dot at `column`, `row` of character `c` is lit. `c` must come
/// from [ledText].
bool dot(String c, int column, int row) =>
    (_glyphs[c] ?? _glyphs[' ']!)[row][column] == '#';

/// Every character the font draws.
Iterable<String> get ledCharacters => _glyphs.keys;
